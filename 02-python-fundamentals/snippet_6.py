a = 15
b = 4

# Floor division: Divides and rounds down to the nearest whole number
floor_division = a // b  # 15 / 4 is 3.75, so this will be 3

# Modulo: Gives the remainder of a division
remainder = a % b  # 15 divided by 4 is 3 with a remainder of 3

# Exponentiation: Raises to the power of
power = b ** 2  # 4 to the power of 2

print(f"Floor Division: {floor_division}")
print(f"Remainder: {remainder}")
print(f"Power: {power}")