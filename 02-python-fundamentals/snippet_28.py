# Convert string to integer
age_str = "25"
age_int = int(age_str)
print(f"Next year you will be {age_int + 1}")

# Convert string to float
price_str = "19.99"
price_float = float(price_str)
print(f"With tax: {price_float * 1.16:.2f}")

# Convert number to string for concatenation
count = 42
message = "The answer is " + str(count)
print(message)