# Start fresh
major_cities = ["Lagos", "Kano", "Ibadan", "Abuja", "Port Harcourt"]
# Add a new city to the end of the list
major_cities.append("Benin City")
print(f"After append: {major_cities}")
# Insert at a specific position (index 1)
major_cities.insert(1, "Onitsha")
print(f"After insert: {major_cities}")
# Change an existing item

major_cities[2] = "Kano (Metropolis)"