language = "Python"
# Access individual characters
print(f"First character: {language[0]}")   # P
print(f"Last character: {language[-1]}")   # n
# Slicing: Get a substring [start:end] (end is exclusive)
print(f"First three: {language[0:3]}")     # Pyt
print(f"From index 2 onwards: {language[2:]}")  # thon