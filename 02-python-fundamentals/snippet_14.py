major_cities = ["Lagos", "Kano", "Ibadan", "Abuja", "Port Harcourt"]

# Access the first item (at index 0)
first_city = major_cities[0]
print(f"The first city is: {first_city}")
# Access the third item (at index 2)
third_city = major_cities[2]
print(f"The third city is: {third_city}")
# Negative indexing starts from the end
last_city = major_cities[-1]
print(f"The last city is: {last_city}")